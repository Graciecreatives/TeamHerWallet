import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage()
await page.goto('http://localhost:3000/')
await page.waitForTimeout(2000)
await page.locator('.header-start').click()
await page.getByRole('dialog').waitFor()
assert.ok(await page.getByRole('link', { name: "I'm here to learn", exact: true }).isVisible())
await page.getByRole('button', { name: 'Continue as a creator' }).click()
await page.locator('#signup-name').waitFor()
console.log('PASS creator confirmation separates learner and creator paths')
const result = await page.request.post('http://localhost:3000/api/auth/register', { data: { displayName: 'Cover Tester', email: `cover${Date.now()}@example.com`, password: 'correct horse battery', role: 'creator' } })
assert.ok(result.ok())
await page.goto('http://localhost:3000/login')
await page.getByLabel('Upload class cover image', { exact: true }).waitFor()
await page.getByLabel('Upload class cover image', { exact: true }).setInputFiles('public/images/pottery-480.webp')
await page.getByText('Your uploaded image is selected.', { exact: true }).waitFor({ timeout: 60000 })
const url = await page.locator('.class-cover-upload > img').getAttribute('src')
assert.match(url, /^https:\/\/learnpurse-images\./)
assert.equal((await page.request.get(url)).status(), 200)
assert.equal(await page.locator('.preview-pane .cover-photo').getAttribute('src'), url)
await page.reload()
await page.getByText('Your uploaded image is selected.', { exact: true }).waitFor()
assert.equal(await page.locator('.class-cover-upload > img').getAttribute('src'), url)
console.log('PASS actual R2 upload, live course preview and reload persistence')
await browser.close()
