import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { chromium } from 'playwright'
const evidence = JSON.parse(await readFile(`${process.env.JCODE_SCRATCH_DIR}/classroom-evidence.json`, 'utf8'))
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
await page.goto(`http://localhost:3000/class/${evidence.id}?access=${evidence.token}`)
await page.getByRole('heading', { name: 'Your classroom', exact: true }).waitFor()
await page.getByRole('link', { name: 'Join live class', exact: true }).waitFor()
assert.ok(await page.getByText('Updated: please bring two pencils.', { exact: true }).isVisible())
await page.getByLabel('Your message', { exact: true }).fill('Browser check: see you in class!')
await page.getByRole('button', { name: 'Send message', exact: true }).click()
await page.getByText('Browser check: see you in class!', { exact: true }).waitFor()
await page.screenshot({ path: `${process.env.JCODE_SCRATCH_DIR}/classroom-desktop.png`, fullPage: true })
await page.setViewportSize({ width: 390, height: 844 })
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
await page.screenshot({ path: `${process.env.JCODE_SCRATCH_DIR}/classroom-mobile.png`, fullPage: true })
console.log('PASS paid learner browser classroom, join link, instructions, sending message and mobile layout')
const context = await browser.newContext()
const [name, ...values] = evidence.cookie.split('=')
await context.addCookies([{ name, value: values.join('='), url: 'http://localhost:3000' }])
const teacher = await context.newPage()
await teacher.goto('http://localhost:3000/login')
const entry = teacher.locator('.listing').filter({ has: teacher.getByRole('heading', { name: 'Live Yoruba Classroom Check', exact: true }) })
await entry.getByRole('button', { name: 'Classroom & learner messages', exact: true }).click()
await entry.getByRole('heading', { name: 'Manage classroom', exact: true }).waitFor()
await entry.getByText('Browser check: see you in class!', { exact: true }).waitFor()
await entry.getByLabel('Your message', { exact: true }).fill('Teacher browser reply: welcome!')
await entry.getByRole('button', { name: 'Send message', exact: true }).click()
await entry.getByText('Teacher browser reply: welcome!', { exact: true }).waitFor()
await page.getByRole('button', { name: 'Refresh classroom' }).click()
await page.getByText('Teacher browser reply: welcome!', { exact: true }).waitFor()
console.log('PASS creator studio inbox and teacher reply visible to learner')
await browser.close()
